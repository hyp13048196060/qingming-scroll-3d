class Reliability(str, Enum):
    """尺寸可信度。写进统计报告,也写进文档。"""

    A = "A"  # 有文献或实物旁证
    B = "B"  # 由 A 级推算,误差随层数放大
    C = "C"  # 为观感/工程可行性选定,无考据支撑


