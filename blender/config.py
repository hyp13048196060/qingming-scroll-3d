class River:
    """汴河。河宽与深由漕船尺度反推 —— 船宽须显著小于河宽才能双向通航。"""

    WIDTH = 16.5      # 河面宽. Reliability B
    DEPTH = 1.5       # 水深. Reliability B
    # 河道走向:沿 Y 轴延伸,虹桥正交跨越
    #
    # 长度取到**远景地裙的外缘**(±300)而不是某段"重点区"。
    #
    # ⚠️ 这个数以前是 240,正好等于 Site 的细致地面范围 ±120。后果是:
    #    在 |y| > 120 处,河水已经没有了、而岸上也没铺地(地裙在
    #    |x| < 10 处留了一条通廊给河),于是**河下游是一条空的沟**。
    #    俯视图上它是画面两侧的两条灰边;站在桥面顺着河望下去,
    #    它是地平线上一块白色的洞。渲出来才发现。
    #    河一直流到雾里去,这是原画的样子,也是唯一不会在别处
    #    再冒出一个洞的取法。
    LENGTH = 600.0    # = 2 × Site.FAR. Reliability C

    # 岸线放样参数
    BANK_SLOPE = 0.55       # 河岸边坡(水平/垂直). Reliability C
    BUND_WIDTH = 2.2        # 纤道宽度. Reliability C

    # 驳岸压顶石:高出岸面 COPING_RISE,自水边向岸内出 COPING_WIDE。
    # **从 build/02_river.py 搬到这里**,理由同下面的 STEP_*:06 要按
    # "压顶之外"来定台阶的起点,而它原先只存在于 02 的模块常量里。
    COPING_RISE = 0.12
    COPING_WIDE = 0.40

    # —— 下河踏步的落点 ——
    #
    # 为什么这一条要从 `build/02_river.py` 提到这里:
    #   踏步是**驳岸上唯一一处向岸内伸进去的东西** —— 它自 x=8.75 起
    #   一级一级往里退,总共伸进岸里约 2m,正好压在柳树的栽植带
    #   (Tree.X_BAND 8.70→9.65)上。两处各写一份坐标的后果是:
    #   02 把踏步挪一米,06 照旧在**原位**栽树,于是树从台阶里长出来 ——
    #   而两边各自的校验都是绿的(树的 x 在带内、踏步的位置也对),
    #   因为**没有任何一处知道对方的存在**。
    #   所以坐标放这里,栽树与校验都从这里读。
    #
    # 形如 (岸侧, 踏步中心 y)。两侧的落点**刻意不对称** ——
    # 对称的两处下河点看着像图纸,不像用出来的。
    STEP_SITES = ((1, -22.0), (1, 34.0), (-1, 30.0), (-1, -30.0))
    # 每处踏步的级数。**原先四处不一样**(两处 5 级、两处 4 级,靠省略
    # 默认参数实现的),提到配置时统一成 4 级 —— 这是**有意的改动**,
    # 不是重构:级数不同就得出两种伸出量,而 STEP_INNER_X 只能声明一个,
    # 校验器便会拿错的那个去核。四处的差异本来也没人看得出来。
    STEP_N = 4
    STEP_HALF_Y = 1.5       # 踏步沿 y 的半宽(02 的 `y_c ± 1.5`)
    STEP_INNER_X = 2.20     # 自 8.75 向岸内的最大伸出量(= STEP_N × step_d 约数)
    # 栽树避让台阶时,除了台阶自身的半宽外再多让出来的量。
    # 台阶不宽,但**树冠宽**(CANOPY_R 最大 3.4m)—— 只让开台阶的实体,
    # 枝条仍会横在台阶上方,人从台阶下河要从柳条里钻过去。
    STEP_MARGIN = 1.60


# ==========================================================================
# 场地布置
#
# 各分区在平面上的位置。所有 builder 都从这里取坐标,不各自硬编码 ——
# 否则"把城门往南挪 5 米"会变成一次全局搜捕。
