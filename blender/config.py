# ==========================================================================
# 自检
#
# 导入本模块时立刻跑一遍关键不等式。尺寸链一旦被改错,
# 应该在这里就炸掉,而不是等到渲染出一座形制错误的桥。
# ==========================================================================
def _self_check() -> None:
    errs: list[str] = []

    # 拱顶净空必须容得下眠桅的船。
    # 用实算值而不是标称下限 —— 标称值只是给文档看的,几何才是真相。
    clr = Bridge.clearance_actual()
    if clr < Bridge.CLEARANCE_MIN:
        errs.append(
            f"实算通航净空 {clr:.3f}m 低于断言下限 {Bridge.CLEARANCE_MIN}m"
        )
    if clr <= Boat.AIR_MAX:
        errs.append(
            f"实算通航净空 {clr:.3f}m 不足以让眠桅船高 {Boat.AIR_MAX}m 通过,"
            f"画中'船正穿桥'的情节不成立"
        )

    # 吃水必须小于水深,否则船底触泥
    if Boat.DRAFT_MAX >= River.DEPTH - 0.1:
        errs.append(
            f"吃水 {Boat.DRAFT_MAX}m 相对水深 {River.DEPTH}m 过深,船会搁浅"
        )

    # 河宽须容得下两船并行
    if River.WIDTH < Boat.BEAM * 2 + 2.0:
        errs.append("河宽不足以让两条漕船并行交会,与'漕运繁忙'的设定矛盾")

    # 拱轴几何自洽
    r = Bridge.radius()
    if abs(r * math.sin(Bridge.half_angle()) - Bridge.SPAN / 2) > 1e-9:
        errs.append("拱轴半径与净跨不自洽")
    if Bridge.SYS2_RADIAL_OFFSET - Bridge.SYS1_RADIAL_OFFSET + 1e-9 < (
        Bridge.SYS1_DEPTH / 2 + Bridge.SYS2_DEPTH / 2
    ):
        errs.append(
            "两系统拱骨的径向偏心不足以分开两层,会互相穿模 —— "
            "偏心须 ≥ 两系统半厚之和"
        )
    if abs((Bridge.RISE - r) + r * math.cos(Bridge.half_angle())) > 1e-9:
        errs.append("拱轴圆心高度与起拱点不自洽")

    # 屋面形制白名单必须真的禁掉硬山
    if set(Bridge.__dict__) & set(Building.ROOF_FORBIDDEN):
        errs.append("屋面无硬山顶(北宋尚无此形制)")

    # —— 场地 ——
    # 拱桥轴线与城门洞轴线的平面距离必须 >15m,否则远景没有层次
    if Site.gate_offset_from_bridge() <= 15.0:
        errs.append(
            f"拱桥与城门在平面上的偏移只有 {Site.gate_offset_from_bridge():.1f}m,"
            f"须 >15m,否则两层景深会叠在一起"
        )
    # 金刚墙必须落在水面**之外**的岸上,否则拱脚泡在水里,会被淘空
    if Site.ABUTMENT_FACE <= Site.WATER_EDGE:
        errs.append(
            f"金刚墙内侧面({Site.ABUTMENT_FACE})没有落在水面边缘"
            f"({Site.WATER_EDGE})之外 —— 拱脚会泡在水里,形制不成立"
        )
    # 分区必须自西向东单调递增,否则街道会压在河道上
    _bands = (Site.WATER_EDGE, Site.ABUTMENT_FACE, Site.BUND_OUTER,
              Site.STREET_OUTER, Site.MARKET_OUTER, Site.WALL_INNER, Site.BANK_OUTER)
    if any(a >= b for a, b in zip(_bands, _bands[1:])):
        errs.append(f"岸上分区未严格递增:{_bands}")
    # 城建在岸上,不能压到河
    if Site.WALL_INNER <= Site.STREET_OUTER:
        errs.append("城墙内缘落在街道带以内")
    # 河道必须铺满整个建模范围。
    # ⚠️ 这条是补上来的,因为漏了它真的在场景里留过一个洞:
    #    远景地裙在 |x| < Site.ABUTMENT_FACE 处给河留了通廊,
    #    若河道自身比 FAR 短,通廊的尽头就是一块虚空 ——
    #    俯视图上看得见,站在桥上顺河望下去也看得见。
    if River.LENGTH < 2 * Site.FAR:
        errs.append(
            f"河道长度 {River.LENGTH}m 短于建模外缘 {2 * Site.FAR}m —— "
            f"地裙为河留出的通廊尽头会露出虚空"
        )

    # 人物三张按姿态名索引的表必须覆盖同一组姿态。
    # ⚠️ 包在 try 里会失去意义 —— 这里就是要让它炸。
    Character.check_tables()
    # 装配层的分布带引用的姿态名、以及网页摆动契约的覆盖,同样要查。
    Assembly.check_tables()

    # 推车人握点的记录值必须真的落在车前柄的延长线上 —— 这一条是
    # "写在注释里的数"与"几何真相"之间唯一的桥。它若错了,推车的人
    # 会扶在车把前的空气里,而预览图上看着只是"手离车把近了点"。
    if Assembly.PUSH_GRIP_Y <= 0.0:
        errs.append("推车握点在身体前方必须为正 —— 负数意味着手落在车架之后")

    if errs:
        raise AssertionError("config.py 自检失败:\n  - " + "\n  - ".join(errs))


