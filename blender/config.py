    def check_tables(cls) -> None:
        """
        分布带引用到的姿态、以及两张姿态表的键,必须与 `Character.POSES` 一致。

        ⚠️ 这条断言挡的是本项目的**老朋友**:写死的清单漏一项时不报错,
           只是静默少做一点。`BANDS[*]["poses"]` 里写错一个姿态名,
           原来的后果是"那一种人一个也不会出现",而汇总里 `placed = 48`
           照样成立(别的姿态按余额补上了)。改成先查覆盖,错名当场炸。
        """
        poses = set(Character.POSES)
        for band in cls.BANDS:
            bad = set(band["poses"]) - poses
            if bad:
                raise AssertionError(
                    f"分布带「{band['name']}」引用了不存在的姿态 {sorted(bad)};"
                    f"`Character.POSES` 只有 {sorted(poses)}"
                )
        if set(cls.POSE_SPEC) != poses:
            raise AssertionError(
                f"Assembly.POSE_SPEC 覆盖的姿态与 POSES 不一致:"
                f" 多出 {sorted(set(cls.POSE_SPEC) - poses)}、"
                f"缺少 {sorted(poses - set(cls.POSE_SPEC))}"
            )
        # 每条带必须**显式声明**自己是不是"会走动的带",且声明要与姿态
        # 配比算出来的结果一致。
        #
        # ⚠️ 这条断言第一版写的是"任何一条带的姿态速度全为零就报错",
        #    而它**当场就炸在了「船上」上** —— 船上只有撑船的,本来就该
        #    站定。第一版把一条**刻意的编排**当成了事故。
        #    正确的形状不是"禁掉站定带",而是"站定必须被说出来":
        #    漏写 `moving` 是事故,写了 `moving=True` 却全是站定姿态也是事故,
        #    两个方向都拦得住,而`船上`这种正当情形只需写一行 `False`。
        #    这也是本项目的一贯做法 —— 把"静默的默认值"换成"必须写出来的声明"。
        for band in cls.BANDS:
            walks = any(cls.POSE_SPEC[p]["speed"] > 0 for p in band["poses"])
            if "moving" not in band:
                raise AssertionError(
                    f"分布带「{band['name']}」没有声明 `moving` —— "
                    f"这一带有{'会' if walks else '不会'}走动的人,请写明"
                )
            if bool(band["moving"]) != walks:
                raise AssertionError(
                    f"分布带「{band['name']}」声明 moving={band['moving']},"
                    f"而它的姿态配比算出来{'会' if walks else '不会'}走动 —— "
                    f"两者必须一致"
                )


