    # ⚠️ 不是自由参数 —— 它被 STRAND_FLOOR 夹住:枝尖不得低于
    #    `max(0.0, 附着点高 − STRAND_DROP上限 × 系数)`。所以真正决定
    #    "柳条垂到哪"的是 TRUNK_H + CANOPY_H 与 STRAND_FLOOR 之差。
    STRAND_DROP = (1.6, 3.0)
    # 垂枝尖距地的下限。**这一条既是观感也是通行的需要**:柳长在岸顶,
    # 垂条扫到人脸上就挡住河景了。0.35m 是"垂得低但不到地"。
    STRAND_FLOOR = 0.35
    # 每株的垂枝数。**这个数返工时翻了三倍**:第一版 24–38 条是
