class Tree:
    """
    柳树。

    **存在性是 A 级**:原画沿汴河两岸柳树成行,这是全卷最显眼的植被,
    不可能看错。虹桥两端、河岸沿线都有,且画法上是"垂柳"无疑 ——
    枝条下垂到接近水面。

    **尺寸全是 C 级**:散点透视图量不出树高。下面这些区间是按
    "垂柳该长成什么样"的比例定的,并参考了当代北方旱柳的实际尺寸。
    它们不是从原画量得的数,不得当成考据结论引用。

    ⚠️ 这段文字原先写的是"主干高约为总高的 1/3,冠幅略大于树高的一半"。
       前一半**从来没被代码实现过**(当时根本没有独立的冠高),后一半
       与当时的 CANOPY_R 也对不上。所以现在把比例**按下面的区间中值
       算出来写在这**,而不是凭印象写一句话:

           净干高   (2.8+4.0)/2 = 3.4 m
           冠高     (3.8+5.2)/2 = 4.5 m   → 树高  7.9 m
           净干 / 树高  = 0.43
           冠径     (2.2+3.2)×2 = 5.4 m   → 冠径 / 树高 = 0.68
           冠高 / 冠径  = 0.83            ← 立着,不摊成伞

       改动上面任一个区间,这段文字就得跟着重算 —— 它是**结论**,
       不是**依据**。**这份文档里的每一个比值都必须在代码里有对应的
       算式**,否则就会重演前面两次返工:文字描述了一种树,代码建了另一种。

    为什么给**区间**而不是定值:原画里没有两株柳树是一样的。写成定值
    再乘一个随机扰动,得到的是"一株树复制了很多份"的观感 —— 植株的
    变化在轮廓上,不在缩放上(缩放只会得到大小不同的同一株树)。
    所以主干高、干径、冠幅、垂枝数各给一个区间独立抽取。
    """

    # ⚠️ 这组数**返工过两次**,第二次的原因值得记下来:
    #
    #   【第一次】只有 TRUNK_H,没有单独的冠高 —— 于是"树高"就是 TRUNK_H
    #   (2.4–3.6m),而 CANOPY_R 是 2.2–3.4m。**冠幅半径 ≈ 树高**。
    #   渲出来是一堆从地上散开的三角架。而文档写的是"主干高约为总高的
    #   1/3" —— 文档说的是对的,代码从没实现过那件事。
    #
    #   【第二次】加上了冠高、枝条也真的向上举了,渲出来仍然不像柳:
    #   垂枝是一根根**看得见的线**,可以透过树看见对面;枝条末端还戳在
    #   叶幕外头,像几根天线。根因是**几何构成错了**,不是参数没调好 ——
    #   只用"从枝尖垂下的线"表现叶,永远得不到"一蓬"的观感,因为枝条
    #   本身没有体积,而线之间是空气。所以第二次返工改的是**结构**:
    #   加了 `_crown_shell()`(一层带噪声的钟形叶壳)给出"蓬"的团块感,
    #   垂枝退回去做**边缘的破碎**,不再承担整株叶量。
    #
    #   【第三次】叶壳加上之后渲出来像**蘑菇** —— 一顶光溜的伞盖底下
    #   挂一圈须。问题不在参数量而在两处:叶壳的剖面像伞盖(最宽处偏下,
    #   顶上收成一个圆顶),垂枝又**只从底面挂着**。柳的枝条是**披**
    #   在整株上的:从冠顶一直到大半腰都有枝条往外斜挂出去。所以这一版
    #   把剖面改成**卵形**(最宽处移到冠高的 0.56),并让垂枝挂满
    #   冠高的 0–0.90、沿壳面往外披。见 `_willow()` 里挂载点那段。
    #
    # 现在是:净干 0.43 树高 · 冠径 0.56 树高 · 冠高/冠径 1.02。
    # 后一个比值最要紧 —— 它**不小于 1** 说明冠是立着的卵形,
    # 摊成伞就是因为这个数太小。

