class Site:
    """
    紧凑高密度沙盘。坐标系(Blender,Z-up):

        X —— 东西向,虹桥沿 X 跨越汴河
        Y —— 南北向,汴河沿 Y 流淌
        Z —— 高度,水面与两岸街道均在 z = 0

    平面分区(以东岸为例,西岸镜像对称):

        x:  0 ── 8.25 ── 10 ── 12.2 ─────── 21.2 ────── 58 ─── 76.4
            水面   收分  纤道      街道          市井       城墙
                   ▲      ▲         ▲
                   │      │         └ 沿街店铺,檐口朝街
                   │      └ 2.2m 纤道(拉纤用,见《东京梦华录》)
                   └ 金刚墙内侧面 = 净跨 20 的一半

    ⚠️ **一处必须说清的尺寸关系**

        `Bridge.SPAN = 20` 要求金刚墙内侧面在 x = ±10;
        `River.WIDTH = 16.5` 要求水面边缘在 x = ±8.25。
        两者差 1.75m。这两个数来自不同的研究(桥的跨度推算 / 河的
        宽度推算),原画没有比例尺可以把它们严格对齐。

        处置:让**净跨比河面宽**,金刚墙落在岸上、**离开水边 1.75m**。

        这不是将就,而是本就该如此 —— 桥台必须坐在稳固的岸土上。
        桥台若贴着水边砌,河水一淘刷,拱脚就空了。宋代造桥对此有
        明确认识,今天也一样。

        于是:
            · 拱从 **x = ±10、z = 0** 起拱,落点正好在岸面标高上;
            · 水面止于 x = ±8.25,岸线由驳岸(河道 builder 建)收住;
            · 8.25 → 10 这 1.75m 是岸顶的**驳岸压顶带**,不是水面。

        遗留的不确定性(如实声明,Reliability C):
        原画量不出"桥台内侧面到水边"的具体距离。取 1.75m 是让
        两个来自不同来源的尺寸都能成立的最小改动,不是考据结果。
        docs/01 中同样声明。
    """

    # —— 沿河方向 ——
    #
    # **细致地面的范围**,不是场景的边界。|y| 超过这里之后,两岸改由
    # 远景地裙(粗分块、带起伏)接手,再远交给雾。
    # 河道不走这个范围 —— 它一直铺到 FAR,否则下游会空出一条沟
    # (见 River.LENGTH 处的说明)。
    Y_MIN = -120.0
    Y_MAX = 120.0

    # 场景建模外缘。超过这里只有雾,不再有几何。
    FAR = 300.0

    # —— 横向关键位置(取正值,西岸取负) ——
    #
    # 这四个数**由 Bridge/River 算出**,不手写。手写的话,有人改了
    # 桥的净跨而没改这里,驳岸就会和拱脚错开一条缝,而且看不出为什么。
    WATER_EDGE = River.WIDTH / 2          # 8.25,水面边缘
    ABUTMENT_FACE = Bridge.SPAN / 2       # 10.0,金刚墙内侧面
    BUND_OUTER = ABUTMENT_FACE + River.BUND_WIDTH      # 12.2
    STREET_OUTER = BUND_OUTER + 9.0                    # 21.2

    MARKET_OUTER = 52.0     # 市井带外缘(店铺进深到此为止). Reliability C
    WALL_INNER = 58.0       # 城墙内缘(靠河一侧). Reliability C
    BANK_OUTER = 108.0      # 岸面建模外缘,再远交给雾. Reliability C

    STREET_WIDTH = 9.0      # 沿河主街宽度. Reliability C

    # —— 城门与城墙 ——
    #
    # 城门在东城墙上,城墙沿 Y 走向(与汴河平行)。
    # 城门洞沿 X 方向穿过城墙,轴线是直线 y = GATE_Y。
    # 虹桥的轴线是直线 y = 0。二者**平行且相距 |GATE_Y|** ——
    # 这就是"拱桥与城门平面投影不共线(偏移 > 15m)"的落实。
    #
    # ⚠️ 原画是散点透视,给不出可靠的平面关系。把城墙摆成与河平行、
    #    城门放在下游 38m 处,是为了让"从桥上望向城门"这条视线
    #    能同时看到虹桥、河道与城楼三层景深 —— 这是**取景需要**,
    #    不是对原画平面的复原。Reliability C。
    GATE_Y = -38.0
    WALL_X = 58.0 + 18.41 / 2   # 城墙中心线 = 内缘 + 半个墙厚

    # —— 沿河的分段(供 04_buildings 布置店铺) ——
    # 虹桥两端要留出桥头空地,不能直接怼上店铺
    BRIDGE_CLEAR_Y = 14.0   # 桥轴线两侧各留 14m 空档

    @classmethod
    def gate_offset_from_bridge(cls) -> float:
        """拱桥轴线与城门洞轴线的平面距离(米)。"""
        return abs(cls.GATE_Y)



class Boat:
    """
    漕船(运粮船)。

    过桥是这幅画的核心情节:船正要穿过虹桥,桅杆已经放倒(眠桅),
    船工在桥上下吆喝指挥。所以本作品必须保证:
        - 满载吃水 ≤ DRAFT_MAX,否则船会搁浅在河里;
        - 眠桅后的总高 ≤ AIR_MAX,否则桅杆会撞上桥腹。
    这两条是硬断言,写进 validate_scale.py。
    """

    DRAFT_MAX = 1.28       # 满载吃水上限. Reliability B
    AIR_MAX = 4.00         # 眠桅后水面以上总高上限. Reliability B
    LENGTH = 11.2          # 船长. Reliability C
    BEAM = 3.1             # 船宽. Reliability C
    HULL_DEPTH = 1.55      # 型深. Reliability C
    MAST_HEIGHT = 7.4      # 立桅总高(过桥前须放倒). Reliability C


