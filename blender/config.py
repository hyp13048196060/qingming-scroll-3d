class Human:
    """
    人体尺度 —— **全场景的"人的高度"只有这一个数**。

    ⚠️ 为什么单独开一个类、而不是把它塞进 Prop 或 Character:
       因为它是**量别人的尺子**。幌子下缘够不够高、门洞够不够过、
       栏杆够不够挡、船舱够不够站 —— 这些判据全都要拿它去比。
       一旦有两处各写各的 1.70/1.75,就会有一处先改、另一处悄悄过期,
       而两处都"看着像那么回事"。单一来源,改一处就全改。

    ⚠️ **可靠性 C 级。** 这个数**不是从原画量出来的** —— 原画没有比例尺,
       张择端也没有画过带刻度的参照物。它的依据是两条:
         ① 宋代墓葬出土的尸骨身高研究普遍给出成年男性均值 1.64–1.72m;
         ② 壁画、俑、传世器物的比例关系与之相容。
       取 1.70 是这个区间的中值,配得上"看起来是这么个人"。
       **它不构成"北宋汴京人平均身高 1.70m"的结论。**
       详见 docs/01-复原依据与考据.md 与 docs/08-已知局限与未做还原.md。
    """

    STATURE = 1.70
    # 净空余量:布幌、门洞、桥下这些"人要从底下过"的地方,
    # 下缘须高出**站直的人**这么多。0.10m 是留给发髻与帽子的 ——
    # 宋人戴幞头/巾帽,顶高不止 1.70。
    HEAD_CLEAR = 0.10

    @classmethod
    def headroom(cls) -> float:
        """人从底下走过所需的最小净空(m)。"""
        return cls.STATURE + cls.HEAD_CLEAR


# ==========================================================================
# 人物
#
# 与 `Human` 的分工必须分清,否则两处迟早各写各的:
#   · `Human`    —— **一条尺子**。它只有"人多高",给幌子、门洞、船舱去比。
#   · `Character`—— **一具身体**。它有关节、有姿态、有骨架,给网页去驱动。
# 所以这里的尺寸**全部由 `Human.STATURE` 按比例导出**,不另立数字。
# 改 `STATURE` 一处,全身跟着变;这正是把尺子和身体分成两类的理由。
# ==========================================================================
class Character:
    """
    蒙皮人物的比例、骨架与姿态。

    ⚠️ **全部为 C 级可靠性。** 原画没有比例尺,散点透视下量不出关节位置。
       下面这些比例取自现代人体测量学的常用比值(头高 ≈ 身高/7.5、
       髋高 ≈ 0.529×身高、指尖 ≈ 0.44×身高),再用"看着像个人"微调。
       **它不是宋代人体测量成果,更不是从原画量出来的。**
       详见 docs/08-已知局限与未做还原.md。

    ⚠️ 本项目**不做面部**。头是一个带收分的方体,没有五官。
       原画里人物的脸在绢上只有几个像素,任何"复原"都是编的。
       近景镜头下这一点看得出来,如实声明,不拿一张贴图去遮。
    """

    S = Human.STATURE

    # —— 关键标高(m)—— 全部是 `STATURE` 的倍数 ——
    HEAD_TOP = S * 1.000          # 1.700
    HEAD_BOT = S * 0.866          # 1.472  头高 0.228 ≈ 身高/7.5
    NECK_TOP = S * 0.866          # 与 HEAD_BOT 同高(颈顶接颅底)
    NECK_BOT = S * 0.832          # 1.414
    CHEST_TOP = S * 0.832         # 1.414
    CHEST_BOT = S * 0.676         # 1.150
    SPINE_TOP = S * 0.676
    SPINE_BOT = S * 0.576         # 0.979
    PELVIS_TOP = S * 0.576
    HIP_Z = S * 0.529             # 0.899  髋关节
    KNEE_Z = S * 0.288            # 0.490
