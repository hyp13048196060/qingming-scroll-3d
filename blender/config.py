# 虹桥(贯木拱桥)
# ==========================================================================
class Bridge:
    """
    汴河虹桥。

    形制依据(《东京梦华录》):
        "其桥无柱,皆以巨木虚架,饰以丹雘,宛如飞虹"
        —— 无柱即**无桥墩**;巨木虚架即**编木拱**(贯木拱)。

    ⚠️ 全桥**无榫卯、无铁钉**,所有构件靠**麻索捆扎**成整体。
    这是北宋虹桥与南渡后闽浙廊桥的分野 —— 后者才大量使用榫卯。
    参考文章中要求做榫卯,本作品**刻意不做**,理由见 docs/01。
    """

    # —— 主尺寸 ——
    SPAN = 20.0          # 净跨(两岸金刚墙之间). Reliability B
    RISE = 5.0           # 拱矢(拱顶高出起拱点). Reliability B
    DECK_WIDTH = 7.8     # 桥面净宽. Reliability B

    # 拱顶最低通航净空。Reliability B
    #
    # ⚠️ 这里修正了原计划的一处内部矛盾。
    #    原计划同时要求"拱矢 5.0"与"拱顶净空 ≥5.0",但这两条无法同时成立:
    #    拱矢 5.0 定的是**拱轴中心线**在拱顶的高度,而通航净空量的是
    #    **结构底面**到水面的距离,结构本身还有厚度。
    #    以本模型为例,拱顶处最低的结构底面是内层(第一系统)拱骨的底:
    #        净空 = RISE − (|内层径向偏心| + 内层拱骨半厚)
    #             = 5.0 − (0.245 + 0.25) = 4.51 m
    #    所以 ≥5.0 是不可能达到的,除非把拱矢抬到约 5.6。
    #
    #    取 4.30 作为**断言下限**:它低于实算值 4.51,留出约 0.21m 余量,
    #    用于吸收水位变化与建模近似;同时它必须大于漕船眠桅总高
    #    Boat.AIR_MAX(4.00),否则画中"船正穿桥"的情节就不成立。
    #    真正的几何断言走 clearance_actual(),见 _self_check()。
    #
    #    ⚠️ 余量 0.21m 偏紧是有意的:拱骨截面是 Reliability C(凭观感定的),
    #       一旦有人把拱骨改粗而忘了复核净空,这里应该立刻炸掉。
    #       实算值随时间变化请看 _self_check() 的报错信息,不要读这个注释。
    CLEARANCE_MIN = 4.30

    @classmethod
    def clearance_actual(cls) -> float:
        """
        拱顶实际通航净空(水面 → 结构最低底面)。

        拱顶处两系统拱骨上下叠置,取更靠下的第一系统:
            净空 = RISE − |第一系统径向偏心| − 第一系统拱骨半厚
        """
        return cls.RISE - abs(cls.SYS1_RADIAL_OFFSET) - cls.SYS1_DEPTH / 2

    # —— 拱骨排布 ——
    # 第一系统:3 根等长拱骨为一组,组间首尾相接
    SYS1_GROUPS = 10
    SYS1_PER_GROUP = 3
    # 第二系统:2 长 2 短共 4 根为一组,与第一系统错开半个组
    SYS2_GROUPS = 11
    SYS2_LONG_PER_GROUP = 2
    SYS2_SHORT_PER_GROUP = 2
    # 横梁:贯穿两系统的横向大梁
    CROSS_BEAMS = 5

    # —— 构件截面 ——
    #
    # 拱骨截面。原画中拱骨极粗壮,是"巨木"而非细杆。
    #
    # ⚠️ 这组数在 v1 调过一次,依据是**渲染反馈而非考据**:
    #    按 0.30/0.34 建出来,两系统合起来的拱带只有 0.63m 厚,
    #    合跨度的 1/32 —— 侧视图里整座桥细得像一根铁丝,与原画
    #    沉厚的观感相差很远(见 screenshots/blender/bridge_v1_side.png)。
    #    这仍然是 Reliability C —— "看着像"不是"考据出"。
    SYS1_DEPTH = 0.50    # 径向厚. Reliability C
    SYS1_WIDTH = 0.46    # 横向宽. Reliability C
    SYS2_DEPTH = 0.46
    SYS2_WIDTH = 0.42

    # 两系统的径向偏心:第一系统偏内、第二系统偏外。
    #
    # ⚠️ 偏心量要两头兼顾,不是一个自由参数:
    #   · 太小 → 两层拱骨互相穿模(下面 _self_check 会拦);
    #   · 太大 → 两层之间裂开一条通长的缝,读起来变成"两座独立的拱",
    #            而不是编木拱那一片**连续的木束**(这是 v1 的另一个毛病)。
    #   所以取"刚好贴合、留 1cm 缝":0.49 ≥ 0.50/2 + 0.46/2 = 0.48 ✓
    #   拱带总厚 = 0.245 + 0.25 + 0.245 + 0.23 ≈ 0.96m ≈ 跨度的 1/21。
    SYS1_RADIAL_OFFSET = -0.245
    SYS2_RADIAL_OFFSET = 0.245

    # —— 横梁 ——
    # 贯穿两片拱肋的关键件,把两片肋连成一个整体并承托桥面。
    #
    # ⚠️ 断面按"拱轴切向 / 径向"命名,不按 X/Z —— 拱是斜的,
    #    用世界轴命名会误导后来的人(改一处忘一处)。
    #
    # ⚠️ 径向高度取 0.84,是**看着渲染图定的**:v2 用 0.36,横梁整个
    #    埋在拱带里,从桥下仰视只看得见一条窄边,像根绷带而不是大梁。
    #    取 0.84 后它基本上占满整个拱带(径向 −0.47 → +0.37),
    #    从下方能看见完整的梁腹,才读得出"横梁"二字。
    CROSS_BEAM_TAN = 0.40       # 沿拱轴切向的宽度
    CROSS_BEAM_RADIAL = 0.84    # 径向高度
    CROSS_BEAM_OFFSET = -0.05   # 梁腹中心相对拱轴中面的径向偏移

    # —— 桥面 ——
    DECK_THICKNESS = 0.14
    # —— 栏杆 ——
    RAIL_POST_SPACING = 1.0   # 栏柱间距. Reliability C —— 见下方说明
    RAIL_POST_SIZE = 0.13
    RAIL_HEIGHT = 1.05

    # —— 索绑 ——
    LASH_RADIUS = 0.075       # 麻索捆扎的视觉半径

    @classmethod
    def radius(cls) -> float:
        """
        拱轴圆弧半径。

        由净跨与拱矢反推:R = (L²/4 + f²) / (2f)
        代入 20 / 5 → (100 + 25) / 10 = 12.5
        """
        return (cls.SPAN**2 / 4 + cls.RISE**2) / (2 * cls.RISE)

    @classmethod
    def center_y(cls) -> float:
        """拱轴圆心高度(起拱点为 y=0 时)。"""
        return cls.RISE - cls.radius()

    @classmethod
    def half_angle(cls) -> float:
        """拱轴半张角(弧度)。"""
        return math.asin((cls.SPAN / 2) / cls.radius())

    @classmethod
    def sys1_step(cls) -> float:
        """第一系统每根拱骨跨越的圆心角。"""
        return 2 * cls.half_angle() / (cls.SYS1_GROUPS * cls.SYS1_PER_GROUP)


