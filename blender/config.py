"""
尺寸与参数的**唯一真相源**。

`build/` 下的脚本只从这里取数,`tasks/validate_scale.py` 也只对照这里断言。
改尺寸只改这一个文件。

⚠️ 关于可靠性的诚实声明(请勿省略)

    下表里的尺寸**不是考古测绘成果**。张择端原画没有比例尺,这些数字来自
    后世研究者(主要是唐寰澄《中国木拱桥》)基于"虹桥栏柱间距约 1m"这一
    单点假定做的**链式推算**。也就是说:

        1m 是整套尺寸链的根节点 —— 它若错了,下游所有尺寸等比地错。

    因此每个常量都带 `Reliability` 标注:

        A —— 有文献或实物旁证,可较有信心
        B —— 由 A 级尺寸推算得来,误差随推算层数放大
        C —— 为观感或工程可行性选定,无考据支撑

    这一点在 docs/01-复原依据与考据.md 中同样声明。**不得**据此宣称
    "考古级复原"或"精确还原"。

已被证伪、禁止使用的数据

    百度百科称虹桥"跨度约 5.28 米"。528.7cm 是**全卷长度**,不是桥跨。
    任何脚本都不得引用该值。
"""

