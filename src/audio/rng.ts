/**
 * 确定性伪随机 —— 乐句表与混响 IR 的唯一随机源。
 *
 * 为什么不用 Math.random
 * ----------------------
 * 本作品的硬性要求是"固定种子 → 完全可复现的原创曲"。Math.random 既不
 * 可播种也不可复现,用它等于把"这首曲子"变成"每次刷新听到的都不一样"。
 * 时间(存一个种子)也不行:换台机器就换一首曲子。
 *
 * 为什么是这个 mulberry32
 * -----------------------
 * 它只有 32 位整数状态、全用 Math.imul 与位移 —— **跨引擎逐位一致**。
 * 用浮点运算实现的随机数(xorshift 的浮点版、sin 散列等)在不同浏览器
 * 上可能差最后一位,而乐句表只要差一位,指纹断言就废了。
 * 周期 2^32,对本作品(几百个音 + 几万个 IR 采样)绰绰有余。
 *
 * ⚠️ 输入种子会先 >>> 0 归一。传进负数或小数不会报错,但**相同种子必须
 *    得到相同序列**这条约定,靠的就是这一步。
 */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return function next(): number {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

